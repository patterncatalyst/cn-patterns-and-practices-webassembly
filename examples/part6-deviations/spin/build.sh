#!/usr/bin/env bash
# examples/part6-deviations/spin/build.sh
#
# Build `cargo-spin.wasm` — a Fermyon Spin HTTP component serving the cargo
# domain — then, with --push, publish it as a Spin OCI application.
#
#   part2 rust provider  (exports patterncatalyst:cargo/*, UNEDITED)
#        +                 -> wac plug ->  cargo-spin.wasm  (exports
#   this crate's handler  (imports patterncatalyst:cargo/*,       wasi:http/handler@0.3.0)
#                          exports wasi:http/handler@0.3.0)
#
# Two build passes, not one:
#
#   1. `spin build -f spin-build.toml` compiles the handler crate. That
#      manifest (generated below, gitignored, never committed) is the only
#      place `[component.cargo-spin.dependencies]` is declared — it is what
#      makes `spin build` regenerate `spin-dependencies.wit` from the already-
#      built provider, which `spin_sdk::dependencies!()` in src/lib.rs then
#      bindgens. The committed spin.toml carries no dependencies section; it
#      ships the far simpler story of "one self-contained wasm".
#   2. `wac plug` composes that raw handler with the provider directly, the
#      same tool and the same shape every other Part 5/6 example in this book
#      uses, producing one self-contained `cargo-spin.wasm` with the import
#      already satisfied. This is what spin.toml (the committed one) and the
#      Dockerfile both reference.
#
# Why bother composing by hand when Spin can satisfy the dependency itself at
# `spin up` time? Packaging: the CRC runtime image (Dockerfile) COPYs exactly
# two files — spin.toml and cargo-spin.wasm — mirroring how every other
# Part 5/6 runtime image here ships one pre-composed artifact rather than a
# provider wasm plus a manifest wiring them together at load time.
#
# ABI note: this component exports `wasi:http/handler@0.3.0` (wasip3), not
# `wasi:http/incoming-handler@0.2.x` — see src/lib.rs's header comment for why
# that is correct for `spin-sdk = "=7.0.0"` and does not affect the
# patterncatalyst:cargo composition below.
#
# Output: ./cargo-spin.wasm (gitignored, see .gitignore) + the intermediate
# ./target/wasm32-wasip2/release/cargo_spin.wasm. Cargo.lock is committed for
# reproducible builds; spin-dependencies.wit and spin-build.toml are
# regenerated every run and gitignored.
set -euo pipefail

export PATH="$HOME/.cargo/bin:$HOME/.local/bin:$PATH"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

PART2="$SCRIPT_DIR/../../part2-building-components"
BUILD_MANIFEST="$SCRIPT_DIR/spin-build.toml"
RUN_MANIFEST="$SCRIPT_DIR/spin.toml"
OUT="$SCRIPT_DIR/cargo-spin.wasm"
IMAGE_REF="ghcr.io/${GHCR_OWNER:-patterncatalyst}/cargo-spin:spinkube"

PUSH=0
for arg in "$@"; do
  case "$arg" in
    --push) PUSH=1 ;;
    *)
      echo "build.sh: FAIL — unknown argument '$arg' (expected: --push)" >&2
      exit 1
      ;;
  esac
done

for tool in cargo spin wac wasm-tools; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    echo "spin/build.sh: FAIL — required tool '$tool' not found on PATH" >&2
    exit 1
  fi
done

echo "spin/build.sh: [1/5] building the Part 2 Rust cargo provider (reused, not edited) ..."
( cd "$PART2/rust" && cargo component build --release )
PROVIDER="$(find "$PART2/rust/target" -name cargo_rust.wasm -not -path '*/deps/*' | head -1)"
[[ -s "$PROVIDER" ]] || { echo "spin/build.sh: FAIL — part2 provider not produced" >&2; exit 1; }

echo "spin/build.sh: [2/5] writing the build-time manifest (declares the patterncatalyst:cargo dependency; gitignored) ..."
cat > "$BUILD_MANIFEST" <<EOF
# Generated by build.sh — do not edit, do not commit (see .gitignore).
# The only manifest in this directory that declares a component dependency;
# it exists so \`spin build\` regenerates spin-dependencies.wit from the Part 2
# provider built above. spin.toml (the shipped manifest) carries no
# dependencies section — see its header comment.
spin_manifest_version = 2

[application]
name = "cargo-spin"
version = "0.1.0"

[[trigger.http]]
route = "/..."
component = "cargo-spin"

[component.cargo-spin]
source = "target/wasm32-wasip2/release/cargo_spin.wasm"
allowed_outbound_hosts = []
[component.cargo-spin.build]
command = "cargo build --target wasm32-wasip2 --release"
watch = ["src/**/*.rs", "Cargo.toml"]

[component.cargo-spin.dependencies]
"patterncatalyst:cargo" = { path = "$PROVIDER" }
EOF

echo "spin/build.sh: [3/5] spin build (regenerates spin-dependencies.wit, compiles the handler) ..."
spin build -f "$BUILD_MANIFEST"
HANDLER="$SCRIPT_DIR/target/wasm32-wasip2/release/cargo_spin.wasm"
[[ -s "$HANDLER" ]] || { echo "spin/build.sh: FAIL — handler component not produced" >&2; exit 1; }
[[ -s "$SCRIPT_DIR/spin-dependencies.wit" ]] || { echo "spin/build.sh: FAIL — spin-dependencies.wit was not regenerated" >&2; exit 1; }

echo "spin/build.sh: [4/5] composing cargo-spin.wasm (wac plug: provider -> handler) ..."
wac plug --plug "$PROVIDER" "$HANDLER" -o "$OUT"
wasm-tools validate "$OUT"

WIT="$(wasm-tools component wit "$OUT")"
if ! grep -q 'export wasi:http/handler@0.3.0;' <<<"$WIT"; then
  echo "spin/build.sh: FAIL — cargo-spin.wasm does not export wasi:http/handler@0.3.0" >&2
  echo "$WIT" >&2
  exit 1
fi
if grep -qE '^\s*import patterncatalyst:' <<<"$WIT"; then
  echo "spin/build.sh: FAIL — cargo-spin.wasm still imports patterncatalyst:cargo/* (plug left it unsatisfied)" >&2
  echo "$WIT" >&2
  exit 1
fi
NON_WASI_IMPORTS="$(grep -E '^\s*import ' <<<"$WIT" | grep -vE '^\s*import wasi:' || true)"
if [[ -n "$NON_WASI_IMPORTS" ]]; then
  echo "spin/build.sh: FAIL — cargo-spin.wasm imports something other than wasi:*:" >&2
  echo "$NON_WASI_IMPORTS" >&2
  exit 1
fi

SHA="$(sha256sum "$OUT" | awk '{print $1}')"
echo "spin/build.sh: wrote $OUT"
echo "spin/build.sh: sha256: $SHA"
echo "spin/build.sh: exports/imports:"
grep -E '^\s*(export|import)' <<<"$WIT"

echo "spin/build.sh: [5/5] OK — cargo-spin.wasm exports wasi:http/handler@0.3.0, imports only wasi:*"

if [[ "$PUSH" -eq 1 ]]; then
  if ! command -v gh >/dev/null 2>&1; then
    echo "spin/build.sh: FAIL — --push requires the 'gh' CLI (authenticated) on PATH" >&2
    exit 1
  fi
  GH_TOKEN="$(gh auth token 2>/dev/null)" || {
    echo "spin/build.sh: FAIL — gh auth token failed; run 'gh auth login' first" >&2
    exit 1
  }
  echo "spin/build.sh: pushing the Spin application to $IMAGE_REF (minikube SpinKube path) ..."
  echo "$GH_TOKEN" | spin registry login ghcr.io -u "${GHCR_OWNER:-patterncatalyst}" --password-stdin
  spin registry push "$IMAGE_REF" -f "$RUN_MANIFEST"
  echo "spin/build.sh: pushed $IMAGE_REF"

  # The CRC path pulls a container image (the Spin runtime around cargo-spin.wasm),
  # not the Spin OCI application — build and push it here too so both deploy
  # targets have their image ready.
  RUNTIME_IMAGE_REF="${RUNTIME_IMAGE_REF:-ghcr.io/${GHCR_OWNER:-patterncatalyst}/cargo-spin-runtime:crc}"
  if command -v docker >/dev/null 2>&1; then
    echo "spin/build.sh: building + pushing the CRC runtime image $RUNTIME_IMAGE_REF ..."
    echo "$GH_TOKEN" | docker login ghcr.io -u "${GHCR_OWNER:-patterncatalyst}" --password-stdin
    docker build --provenance=false -f "$SCRIPT_DIR/Dockerfile" -t "$RUNTIME_IMAGE_REF" "$SCRIPT_DIR"
    docker push "$RUNTIME_IMAGE_REF"
    echo "spin/build.sh: pushed $RUNTIME_IMAGE_REF"
  else
    echo "spin/build.sh: docker not found — skipped the CRC runtime image; build+push it per README before the CRC deploy" >&2
  fi
fi
