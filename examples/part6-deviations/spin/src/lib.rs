// HTTP front door for the cargo domain, as a Fermyon Spin component (ch26).
//
// This is the Spin-native counterpart to `examples/part3-interfaces/http-rust`:
// same route (`GET /cargo/{id}`), same domain, same book-then-get pattern, on
// a different host with a different entrypoint macro. `#[http_service]` plus
// `spin_sdk::http::{Request, Response}` are Spin's ergonomic layer over a wasm
// component's HTTP ABI; `spin_sdk::dependencies!()` is Spin's own composition
// mechanism for satisfying a non-WASI import, equivalent in effect to the
// `wac plug` every earlier example in this book runs by hand (see
// ../../part2-building-components's provider and this crate's build.sh).
//
// ABI note for readers coming from Part 3: `spin-sdk = "=7.0.0"`'s
// `#[http_service]` targets `wasi:http@0.3.0/handler` (wasip3, the async HTTP
// world), a different export than the `wasi:http/incoming-handler@0.2.x`
// every other HTTP example in this book exports. Spin's trigger-http
// (v4.2.4) runs both ABIs natively — `crates/trigger-http/src/wasip3.rs`
// alongside `.../wasi.rs` — so this still serves correctly under
// `spin up`/SpinKube. `cargo-spin.wasm` is a Spin artifact: `spin up` and
// SpinKube serve it directly, while a `wasmtime serve` pipeline or another
// wasi:http 0.2.x host expects the 0.2.x shape Part 3's component exports
// instead. The `patterncatalyst:cargo` import composition underneath is
// unaffected — that interface carries no wasi:http dependency.
//
// Routing follows the same shape as Part 3's http-rust: a known id of
// CARGO-{ORIGIN}-{DEST} is booked (seeding this request's fresh provider
// instance) then read back; everything else legitimately misses -> 404. Spin
// gives each HTTP request its own component instance, so a bare get-cargo on
// a cold instance would always miss — booking first is what makes the single
// request demonstrate a cross-component call that returns data.
use spin_sdk::http::{IntoResponse, Request, Response};
use spin_sdk::http_service;

// Reads `spin-dependencies.wit` (regenerated by `spin build` from this
// manifest's `[component.cargo-spin.dependencies]` entry, see spin.toml) and
// bindgens the `patterncatalyst:cargo/{types,booking}` import. The generated
// module tree lands at the crate root as `patterncatalyst::cargo::...` —
// used directly below, no `bindings::` prefix.
spin_sdk::dependencies!();

use patterncatalyst::cargo::booking::{book_cargo, get_cargo};
use patterncatalyst::cargo::types::{CargoError, Location, RouteSpec};

const DEFAULT_WEIGHT_KG: f64 = 1200.5;
const ARRIVAL_DEADLINE: &str = "2026-12-01T00:00:00Z";

// Minimal UN/LOCODE -> (name, country) lookup for the demo locations, same
// table Part 3's http-rust uses. The provider does not validate name/country,
// so unknown codes fall back to the code itself and an empty country.
fn location_for(unlocode: &str) -> Location {
    let (name, country) = match unlocode {
        "USNYC" => ("New York", "US"),
        "DEHAM" => ("Hamburg", "DE"),
        other => (other, ""),
    };
    Location {
        unlocode: unlocode.to_string(),
        name: name.to_string(),
        country: country.to_string(),
    }
}

fn json_escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn error_status(e: &CargoError) -> (u16, String) {
    match e {
        CargoError::NotFound(m) => (404, m.clone()),
        CargoError::InvalidBooking(m) => (400, m.clone()),
        CargoError::InvalidLocation(m) => (400, m.clone()),
        CargoError::Conflict(m) => (409, m.clone()),
    }
}

fn json_response(status: u16, body: String) -> anyhow::Result<impl IntoResponse> {
    Ok(Response::builder()
        .status(status)
        .header("content-type", "application/json")
        .body(body))
}

#[http_service]
async fn handle_cargo_spin(req: Request) -> anyhow::Result<impl IntoResponse> {
    let path = req.uri().path().to_string();

    let Some(id) = path.strip_prefix("/cargo/").filter(|rest| !rest.is_empty()) else {
        return json_response(
            404,
            r#"{"error":"not found","hint":"GET /cargo/{id}"}"#.to_string(),
        );
    };

    // Known shape CARGO-{ORIGIN}-{DEST}: book (seed) then read back.
    let parts: Vec<&str> = id.splitn(3, '-').collect();
    if parts.len() == 3 && parts[0] == "CARGO" {
        let spec = RouteSpec {
            origin: location_for(parts[1]),
            destination: location_for(parts[2]),
            arrival_deadline: ARRIVAL_DEADLINE.to_string(),
        };
        return match book_cargo(&spec, DEFAULT_WEIGHT_KG) {
            Ok(booking) => match get_cargo(&booking.cargo_id) {
                Ok(cargo) => {
                    let body = format!(
                        "{{\"tracking_id\":\"{}\",\"origin\":\"{}\",\"destination\":\"{}\",\"weight_kg\":{},\"price\":{{\"amount\":\"{}\",\"currency\":\"{}\"}}}}",
                        json_escape(&cargo.tracking_id),
                        json_escape(&cargo.origin.unlocode),
                        json_escape(&cargo.destination.unlocode),
                        cargo.weight_kg,
                        json_escape(&booking.price.amount),
                        json_escape(&booking.price.currency),
                    );
                    json_response(200, body)
                }
                Err(e) => {
                    let (status, msg) = error_status(&e);
                    json_response(status, format!("{{\"error\":\"{}\"}}", json_escape(&msg)))
                }
            },
            Err(e) => {
                let (status, msg) = error_status(&e);
                json_response(status, format!("{{\"error\":\"{}\"}}", json_escape(&msg)))
            }
        };
    }

    // Any other id is never booked, so get-cargo legitimately misses.
    match get_cargo(id) {
        Ok(cargo) => json_response(
            200,
            format!("{{\"tracking_id\":\"{}\"}}", json_escape(&cargo.tracking_id)),
        ),
        Err(e) => {
            let (status, msg) = error_status(&e);
            json_response(status, format!("{{\"error\":\"{}\"}}", json_escape(&msg)))
        }
    }
}
